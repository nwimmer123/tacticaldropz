"""
Turn scripts/11e/cache/base_sizes_extracted.json (raw PDF extraction) into the
frontend data file baseSizeData.js consumed by inferBaseSize() in script.js.

Values that aren't a real fixed mm base ("Hull", "Unique", "Large/Small Flying
Base") are skipped -- those units keep falling through to the existing regex
heuristics in inferBaseSize(), same as before this table existed.
"""
import json
import re

SRC = "scripts/11e/cache/base_sizes_extracted.json"
OUT = "baseSizeData.js"

SKIP_VALUES = {"hull", "unique", "large flying base", "small flying base"}

# Corrections to the app's existing BASE_SIZES catalog (script.js) -- these
# three oval keys were hand-guessed before this chart existed and are off by
# a fraction of a mm (or, for 170x105o, a full 4mm) from GW's real values.
# The dropdown key STRINGS are kept stable (don't break already-placed models'
# saved baseSizeKey references); only the w/h the key resolves to is corrected.
BASE_SIZES_CORRECTIONS = {
    "60x35o":   {"w": 60,  "h": 35.5},
    "90x52o":   {"w": 90,  "h": 52.5},
    "170x105o": {"w": 170, "h": 109},
}
# New catalog entries this chart justifies that weren't in BASE_SIZES before.
BASE_SIZES_ADDITIONS = [
    {"key": "28.5", "w": 28.5, "h": 28.5, "shape": "circle"},
    {"key": "120",  "w": 120,  "h": 120,  "shape": "circle"},
]

def slug(s):
    return re.sub(r"\s+", "-", s.strip().lower())

def value_to_key(raw):
    v = raw.strip()
    vl = v.lower()
    if vl in SKIP_VALUES:
        return None, None

    m = re.match(r"^(\d+(?:\.\d+)?)mm$", v, re.IGNORECASE)
    if m:
        n = m.group(1)
        n = n[:-2] if n.endswith(".0") else n
        return n, "circle"

    m = re.match(r"^(\d+(?:\.\d+)?)x(\d+(?:\.\d+)?)mm\s*Oval Base$", v, re.IGNORECASE)
    if m:
        w, h = float(m.group(1)), float(m.group(2))
        # Map onto the corrected/added catalog keys above (exact value match, no rounding --
        # round(52.5) is banker's-rounded to 52 in Python, which silently broke this before).
        if w == 60 and h == 35.5:
            return "60x35o", "oval"
        if w == 90 and h == 52.5:
            return "90x52o", "oval"
        if w == 170 and h == 109:
            return "170x105o", "oval"
        wk = str(int(w)) if w == int(w) else str(w)
        hk = str(int(h)) if h == int(h) else str(h)
        return f"{wk}x{hk}o", "oval"

    return None, None

data = json.load(open(SRC, encoding="utf-8"))

flat = {}          # normalized unit name -> baseSizeKey
flat_conflicts = set()
qualified = {}      # "faction-slug::unit-slug" -> baseSizeKey
skipped_count = 0

for faction, rows in data.items():
    for r in rows:
        unit_name = r["unit"].strip()
        key, shape = value_to_key(r["base"])
        if key is None:
            skipped_count += 1
            continue

        name_key = unit_name.lower()
        if name_key in flat and flat[name_key] != key:
            flat_conflicts.add(name_key)
        else:
            flat[name_key] = key

        qualified[f"{slug(faction)}::{slug(unit_name)}"] = key

for name_key in flat_conflicts:
    del flat[name_key]

lines = []
lines.append("// AUTO-GENERATED by scripts/11e/10_build_base_size_data.py from GW's official base-size")
lines.append("// chart (scripts/11e/cache/bases.pdf, pp.55-93). Do not hand-edit -- regenerate instead.")
lines.append("// Consumed by inferBaseSize() in script.js as an override before the regex heuristics.")
lines.append("//")
lines.append("// NOTE: this chart also justified hand-applied fixes to BASE_SIZES in script.js:")
lines.append("//   " + json.dumps(BASE_SIZES_CORRECTIONS) + " (corrected dimensions, same key)")
lines.append("//   " + json.dumps(BASE_SIZES_ADDITIONS) + " (new catalog entries)")
lines.append("")
lines.append("// unitName.toLowerCase() -> baseSizeKey (only unambiguous across all factions)")
lines.append("const OFFICIAL_BASE_SIZES_FLAT = " + json.dumps(flat, indent=2, sort_keys=True) + ";")
lines.append("")
lines.append("// 'faction-slug::unit-slug' -> baseSizeKey (faction-qualified, for the rare name collision)")
lines.append("const OFFICIAL_BASE_SIZES_QUALIFIED = " + json.dumps(qualified, indent=2, sort_keys=True) + ";")
lines.append("")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print(f"flat entries: {len(flat)} (conflicts excluded: {len(flat_conflicts)}: {sorted(flat_conflicts)})")
print(f"qualified entries: {len(qualified)}")
print(f"skipped (Hull/Unique/Flying Base): {skipped_count}")
